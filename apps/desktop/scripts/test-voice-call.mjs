#!/usr/bin/env node
import assert from "node:assert/strict";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { dirname, join } from "node:path";
import { createRequire } from "node:module";
import { fileURLToPath } from "node:url";

const require = createRequire(import.meta.url);
const scriptDir = dirname(fileURLToPath(import.meta.url));
const desktopRoot = dirname(scriptDir);
const { createClassroomCallObserver } = require(join(desktopRoot, "dist-electron", "dsh", "voice-call.js"));

const teacher = {
  endpointId: "teacher-01",
  role: "teacher",
  schoolId: "school-01",
  displayName: "王老师",
  fingerprint: "sha256:teacher-key",
};
const classroom = {
  endpointId: "classroom-01",
  role: "classroom",
  schoolId: "school-01",
  classId: "g7-1",
  displayName: "七年一班",
  fingerprint: "sha256:classroom-key",
};

function snapshot({ identity = classroom, peers = [teacher], inbox = [] } = {}) {
  return { started: true, configured: true, lockedRole: "classroom", identity, peers: peers.map((peer) => ({ ...peer, blocked: peer.blocked ?? false })), inbox };
}

function callRow(id, extra = {}) {
  return {
    messageId: id,
    contentType: "NOTIFY",
    from: teacher,
    recipient: classroom,
    body: "机密正文不可朗读：听写错题与个人情况。",
    directive: {
      item: "老师叫号",
      // Exact note generated by mochi_call_student when instruction is present:
      // `请于${when}到${location}；${instruction}` with no trailing period.
      verdicts: [{ student: "林知夏", action: "call", note: "请于下课后到教师办公室；携带私密记录" }],
    },
    ...extra,
  };
}

const root = mkdtempSync(join(tmpdir(), "mochi-voice-call-"));
const dataPath = join(root, "userData", "voice-call-delivery.json");

try {
  const handed = [];
  const observer = createClassroomCallObserver(dataPath, async (request) => {
    handed.push(request);
    return true;
  });

  const initial = snapshot({ inbox: [callRow("old-call-1"), { messageId: "old-notify", contentType: "NOTIFY" }] });
  assert.deepEqual(await observer.observe(initial), { status: "baseline", handedOff: [], attempted: [] }, "the first snapshot is a silent backlog baseline");
  assert.equal(handed.length, 0);
  const firstStore = JSON.parse(readFileSync(dataPath, "utf8"));
  const persisted = readFileSync(dataPath, "utf8");
  assert.equal(firstStore.identities[0].entries.length, 2, "baseline remembers every inbox id");
  assert.equal(persisted.includes("林知夏"), false, "the ledger stores no student names or speech text");
  assert.equal(persisted.includes("私密说明"), false, "the ledger stores no private body or note");

  const fresh = callRow("new-call-1");
  const withFresh = snapshot({ inbox: [...initial.inbox, fresh] });
  const freshResult = await observer.observe(withFresh);
  assert.deepEqual(freshResult, { status: "observed", handedOff: ["new-call-1"], attempted: ["new-call-1"] });
  assert.equal(handed.length, 1, "a new single call is handed off once");
  assert.deepEqual(handed[0], {
    messageId: "new-call-1",
    text: "林知夏，请于下课后到教师办公室。",
  });
  assert.equal(handed[0].text.includes("听写"), false, "the public announcement omits lesson/dictation text");
  assert.equal(handed[0].text.includes("私密"), false, "the public announcement omits private instruction tails");
  assert.equal((await observer.observe(withFresh)).status, "unchanged", "duplicate snapshots do not repeat speech");

  const noInstruction = createClassroomCallObserver(join(root, "no-instruction.json"), (request) => {
    handed.push(request);
    return true;
  });
  await noInstruction.observe(snapshot());
  await noInstruction.observe(snapshot({ inbox: [callRow("no-instruction-call", {
    directive: { item: "老师叫号", verdicts: [{ student: "周同学", action: "call", note: "请到教师办公室。" }] },
  })] }));
  assert.equal(handed.at(-1).text, "周同学，请到教师办公室。", "the no-instruction note retains its generated final period format");

  const restartedSpeech = [];
  const restarted = createClassroomCallObserver(dataPath, (request) => {
    restartedSpeech.push(request);
    return true;
  });
  assert.equal((await restarted.observe(withFresh)).status, "baseline", "restart establishes a new silent baseline");
  assert.equal(restartedSpeech.length, 0, "a queued call is never replayed after restart");
  const afterRestart = snapshot({ inbox: [...withFresh.inbox, callRow("new-call-2")] });
  await restarted.observe(afterRestart);
  assert.deepEqual(restartedSpeech.map((row) => row.messageId), ["new-call-2"]);

  const backpressurePath = join(root, "backpressure.json");
  const backpressureCalls = [];
  let backpressureResult = "busy";
  const backpressure = createClassroomCallObserver(backpressurePath, (request) => {
    backpressureCalls.push(request.messageId);
    return backpressureResult;
  });
  await backpressure.observe(snapshot());
  const backpressured = snapshot({ inbox: [callRow("backpressured-call")] });
  assert.deepEqual(await backpressure.observe(backpressured), {
    status: "observed", handedOff: [], attempted: ["backpressured-call"],
  });
  assert.equal(JSON.parse(readFileSync(backpressurePath, "utf8")).identities[0].entries[0].stage, "deferred",
    "explicit queue backpressure persists a retryable id without speech text");
  backpressureResult = true;
  assert.deepEqual(await backpressure.observe(backpressured), {
    status: "observed", handedOff: ["backpressured-call"], attempted: ["backpressured-call"],
  }, "the same still-present call retries after known non-enqueue backpressure");
  assert.deepEqual(backpressureCalls, ["backpressured-call", "backpressured-call"]);
  assert.equal(JSON.parse(readFileSync(backpressurePath, "utf8")).identities[0].entries[0].stage, "queued");

  const backpressureRestartCalls = [];
  const backpressureRestart = createClassroomCallObserver(backpressurePath, (request) => {
    backpressureRestartCalls.push(request.messageId);
    return true;
  });
  assert.equal((await backpressureRestart.observe(backpressured)).status, "baseline",
    "restart converts outstanding deferred work into the silent backlog baseline");
  assert.equal((await backpressureRestart.observe(backpressured)).status, "unchanged");
  assert.deepEqual(backpressureRestartCalls, [], "restart never replays an already accepted call");

  const revokedPath = join(root, "revoked-during-defer.json");
  const revokedCalls = [];
  const revoked = createClassroomCallObserver(revokedPath, (request) => {
    revokedCalls.push(request.messageId);
    return "busy";
  });
  await revoked.observe(snapshot());
  const deferredCall = snapshot({ inbox: [callRow("revoked-during-defer")] });
  await revoked.observe(deferredCall);
  const revokedSnapshot = snapshot({ peers: [{ ...teacher, blocked: true }], inbox: deferredCall.inbox });
  assert.equal((await revoked.observe(revokedSnapshot)).status, "observed");
  assert.equal(JSON.parse(readFileSync(revokedPath, "utf8")).identities[0].entries[0].stage, "attempted",
    "revoked pairing ends a deferred retry");
  await revoked.observe(deferredCall);
  assert.deepEqual(revokedCalls, ["revoked-during-defer"], "unblocking later does not revive a revoked deferred call");

  const boundedPath = join(root, "bounded-observation.json");
  const boundedCalls = [];
  const bounded = createClassroomCallObserver(boundedPath, (request) => {
    boundedCalls.push(request.messageId);
    return true;
  });
  await bounded.observe(snapshot());
  const burst = snapshot({ inbox: Array.from({ length: 25 }, (_, index) => callRow(`burst-${index}`)) });
  const burstFirst = await bounded.observe(burst);
  assert.equal(burstFirst.attempted.length, 20, "one snapshot invokes at most twenty speech callbacks");
  assert.equal(JSON.parse(readFileSync(boundedPath, "utf8")).identities[0].entries.filter((entry) => entry.stage === "deferred").length, 5,
    "unprocessed valid calls remain deferred for a later authenticated snapshot");
  const burstSecond = await bounded.observe(burst);
  assert.equal(burstSecond.attempted.length, 5);
  assert.equal(boundedCalls.length, 25, "bounded retries eventually hand off every still-current call");

  const rollingPath = join(root, "rolling.json");
  const rollingCalls = [];
  const rolling = createClassroomCallObserver(rollingPath, (request) => {
    rollingCalls.push(request.messageId);
    return true;
  });
  const baselineRows = Array.from({ length: 1_000 }, (_, index) => ({ messageId: `base-${index}`, contentType: "NOTIFY" }));
  await rolling.observe(snapshot({ inbox: baselineRows }));
  const longLivedCall = callRow("long-lived-call");
  await rolling.observe(snapshot({ inbox: [longLivedCall, ...baselineRows.slice(0, 999)] }));
  for (const round of [1, 2]) {
    const churnRows = Array.from({ length: 999 }, (_, index) => ({ messageId: `churn-${round}-${index}`, contentType: "NOTIFY" }));
    const rollingSnapshot = snapshot({ inbox: [longLivedCall, ...churnRows] });
    await rolling.observe(rollingSnapshot);
    if (round === 2) {
      await rolling.observe(rollingSnapshot);
      const ledger = JSON.parse(readFileSync(rollingPath, "utf8")).identities[0].entries;
      assert.equal(ledger.some((entry) => entry.messageId === "long-lived-call"), true, "current inbox ids survive bounded-history trimming");
      assert.ok(ledger.length <= 1_200, "the persisted delivery ledger remains bounded");
    }
  }
  assert.deepEqual(rollingCalls, ["long-lived-call"], "a current call is not replayed when historical ledger ids roll off");

  const untrustedSpeech = [];
  const untrusted = createClassroomCallObserver(join(root, "untrusted.json"), (request) => {
    untrustedSpeech.push(request);
    return true;
  });
  await untrusted.observe(snapshot());
  const invalidRows = [
    callRow("ordinary-notify", { directive: undefined }),
    callRow("generic-call", { directive: { item: "听写", verdicts: [{ student: "林知夏", action: "call", note: "请到办公室。" }] } }),
    callRow("dictation-fail", { directive: { item: "第 5 单元听写", verdicts: [{ student: "林知夏", action: "fail" }] } }),
    callRow("multi-student", { directive: { item: "老师叫号", verdicts: [
      { student: "林知夏", action: "call" },
      { student: "陈同学", action: "call" },
    ] } }),
    callRow("unknown-field", { directive: { item: "老师叫号", verdicts: [{ student: "林知夏", action: "call", privateDestination: "secret" }] } }),
    callRow("malformed-name", { directive: { item: "老师叫号", verdicts: [{ student: "\n林知夏", action: "call", note: "请到办公室。" }] } }),
    callRow("wrong-school", { from: { ...teacher, schoolId: "other-school" } }),
    callRow("wrong-fingerprint", { from: { ...teacher, fingerprint: "sha256:changed" } }),
    callRow("wrong-recipient", { recipient: { ...classroom, endpointId: "other-room" } }),
  ];
  await untrusted.observe(snapshot({ inbox: invalidRows }));
  await untrusted.observe(snapshot({ peers: [{ ...teacher, blocked: true }], inbox: [callRow("blocked-peer-call")] }));
  assert.deepEqual(untrustedSpeech.map((row) => row.messageId), [], "ordinary notices, dictation verdicts, batches, malformed fields and unpaired identities are never spoken");
  await untrusted.observe(snapshot({ peers: [{ ...teacher, blocked: true }], inbox: [callRow("blocked-peer-call")] }));
  assert.deepEqual(untrustedSpeech.map((row) => row.messageId), [], "a blocked former teacher is never spoken");

  const fallbackSpeech = [];
  const fallback = createClassroomCallObserver(join(root, "fallback.json"), (request) => {
    fallbackSpeech.push(request);
    return true;
  });
  await fallback.observe(snapshot());
  await fallback.observe(snapshot({ inbox: [callRow("fallback-call", {
    directive: { item: "老师叫号", verdicts: [{ student: "林知夏", action: "call", note: "请把私人情况说一遍" }] },
  })] }));
  assert.deepEqual(fallbackSpeech.map((row) => row.text), ["林知夏，请查看教室屏幕上的老师通知。"], "unrecognized note formats use a screen-only prompt and never invent a destination");
  const wrongPunctuation = createClassroomCallObserver(join(root, "wrong-punctuation.json"), (request) => {
    fallbackSpeech.push(request);
    return true;
  });
  await wrongPunctuation.observe(snapshot());
  await wrongPunctuation.observe(snapshot({ inbox: [callRow("wrong-instruction-punctuation", {
    directive: { item: "老师叫号", verdicts: [{ student: "林知夏", action: "call", note: "请到教师办公室；私人说明。" }] },
  })] }));
  assert.equal(fallbackSpeech.at(-1).text, "林知夏，请查看教室屏幕上的老师通知。", "a trailing period after instruction is not accepted as an app-generated note");

  const failurePath = join(root, "failure.json");
  const failedCalls = [];
  const failed = createClassroomCallObserver(failurePath, (request) => {
    failedCalls.push(request.messageId);
    throw new Error("audio device unavailable");
  });
  await failed.observe(snapshot());
  const failedRow = snapshot({ inbox: [callRow("failed-once")] });
  assert.deepEqual(await failed.observe(failedRow), { status: "observed", handedOff: [], attempted: ["failed-once"] });
  await failed.observe(failedRow);
  assert.deepEqual(failedCalls, ["failed-once"], "a failed or unknown handoff is not retried automatically");
  assert.equal(JSON.parse(readFileSync(failurePath, "utf8")).identities[0].entries[0].stage, "attempted");

  const changedSpeech = [];
  const changed = createClassroomCallObserver(join(root, "identity-change.json"), (request) => {
    changedSpeech.push(request);
    return true;
  });
  await changed.observe(snapshot());
  const newClassroom = { ...classroom, endpointId: "classroom-02", fingerprint: "sha256:classroom-2", classId: "g7-2" };
  const oldCallAtNewIdentity = snapshot({ identity: newClassroom, inbox: [callRow("identity-backlog")] });
  assert.equal((await changed.observe(oldCallAtNewIdentity)).status, "baseline", "identity changes reset the live baseline and cannot announce the former identity's backlog");
  assert.equal(changedSpeech.length, 0);

  const malformedPath = join(root, "malformed.json");
  writeFileSync(malformedPath, "{broken", "utf8");
  const malformedSpeech = [];
  const malformed = createClassroomCallObserver(malformedPath, (request) => {
    malformedSpeech.push(request);
    return true;
  });
  assert.equal((await malformed.observe(snapshot({ inbox: [callRow("must-not-replay")] }))).status, "storage-unavailable");
  assert.equal(malformedSpeech.length, 0, "a corrupt ledger fails closed instead of risking duplicate speech");

  console.log("voice call handoff tests passed: trusted single-call filtering, restart baseline, persistent dedupe, identity binding, privacy and fail-closed storage");
} finally {
  rmSync(root, { recursive: true, force: true });
}
